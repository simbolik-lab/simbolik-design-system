/**
 * The token build. Validates the token source, resolves it in every context
 * combination through Style Dictionary, and writes the four outputs:
 *
 *   css/tokens.css       CSS custom properties, with theme, density, text-size and layout contexts
 *   css/tailwind.css     a Tailwind theme block that gives the same custom properties utility names
 *   output/tokens.ts     a typed TypeScript module
 *   output/tokens.json   plain JSON, one record per token
 *
 *   npm run tokens:build
 *
 * All four are Build Output. Editing one is a change the next build silently discards.
 */
import StyleDictionary from 'style-dictionary';
import { fileURLToPath } from 'node:url';
import { join, dirname, resolve as resolvePath } from 'node:path';
import { loadTokenSource, combinationKey, tokensFor, TOKENS_DIR_DEFAULT, type TokenSource, type Combination, type LoadedToken } from './lib/load.js';
import { validate } from './validate.js';
import { buildModel, comboFor, valueByContext, mediaQueryFor, substituteDimensions, type Model, type ModelToken } from './lib/model.js';
import { setAtPath, type Group } from './lib/dtcg.js';
import { CONTEXT_CSS, LAYOUT_SWITCH, TAILWIND_NAMESPACE, PREFIX } from './config.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');

function treeFor(source: TokenSource, combo: Combination): Group {
  const tree: Group = {};
  for (const t of tokensFor(source, combo).values()) setAtPath(tree, t.segments, { ...t.token });
  return tree;
}

/**
 * Cross-check: Style Dictionary must resolve every combination to the same literal
 * values the build's own resolver found. Two independent resolvers agreeing is the
 * point; a disagreement means one of them is wrong about the standard.
 */
async function crossCheckWithStyleDictionary(source: TokenSource, model: Model): Promise<void> {
  for (const combo of model.combos) {
    const sd = new StyleDictionary({
      tokens: treeFor(source, combo),
      usesDtcg: true,
      log: { verbosity: 'silent', warnings: 'disabled' },
      platforms: { resolve: { transforms: [] } },
    });
    const { allTokens } = await sd.getPlatformTokens('resolve');
    const key = combinationKey(combo);
    for (const sdToken of allTokens) {
      const path = sdToken.path.join('.');
      const ours = model.byPath.get(path);
      if (!ours) throw new Error(`Style Dictionary found "${path}" but the build model did not.`);
      const a = JSON.stringify(sdToken.$value);
      const b = JSON.stringify(ours.resolved[key]);
      if (a !== b) throw new Error(`Resolvers disagree on "${path}" in ${key}:\n  style-dictionary: ${a}\n  build:            ${b}`);
    }
    if (allTokens.length !== model.tokens.length) throw new Error(`Style Dictionary resolved ${allTokens.length} tokens, the build model ${model.tokens.length}.`);
  }
}

const header = (what: string) =>
  `/* GENERATED by the simbolik token build — do not edit. ${what}\n * Source: simbolik/tokens/. Rebuild with: npm run tokens:build */\n`;

function declarations(decls: Record<string, string>, indent = '  '): string {
  return Object.entries(decls).map(([n, v]) => `${indent}${n}: ${v};`).join('\n');
}

function formatCss(model: Model): string {
  const defaultKey = combinationKey(model.defaults);
  const out: string[] = [header('CSS custom properties.')];
  const emitted = model.tokens.filter((t) => t.emitted);

  const rootDecls: Record<string, string> = {};
  for (const t of emitted) Object.assign(rootDecls, t.css[defaultKey]);
  out.push(`:root {\n${declarations(rootDecls)}\n}\n`);

  const forcedBlocks: string[] = [];
  for (const [axis, { values, default: def }] of Object.entries(model.axes)) {
    const cfg = CONTEXT_CSS[axis];
    if (!cfg) throw new Error(`build/config.ts has no CSS strategy for the "${axis}" axis.`);
    if (cfg.kind === 'attribute' && cfg.over) {
      out.push(...formatLaidOver(model, axis, emitted.filter((t) => t.over === axis)));
      continue;
    }
    const onAxis = emitted.filter((t) => t.axis === axis);
    const dependent = emitted.filter((t) => t.dependent[axis]?.length);
    if (onAxis.length === 0) continue;
    out.push(`/* ${axis}: ${values.join(' | ')} (default ${def}) */`);

    for (const context of values) {
      const key = combinationKey(comboFor(model, axis, context));
      const decls: Record<string, string> = {};
      for (const t of onAxis) Object.assign(decls, t.css[key]);
      for (const t of dependent) for (const name of t.dependent[axis]!) decls[name] = t.css[key]![name]!;
      if (cfg.kind === 'attribute') {
        if (cfg.colorScheme) decls['color-scheme'] = context;
        const selector = context === def ? `:root,\n[${cfg.attribute}="${context}"]` : `[${cfg.attribute}="${context}"]`;
        out.push(`${selector} {\n${declarations(decls)}\n}\n`);
        const pref = cfg.systemPreference?.[context];
        if (pref) {
          out.push(`@media ${pref} {\n  :root:not([${cfg.attribute}]) {\n${declarations(decls, '    ')}\n  }\n}\n`);
        }
      } else if (!cfg.attribute) {
        if (context !== def) out.push(`@media ${mediaQueryFor(model, axis, context)} {\n  :root {\n${declarations(decls, '    ')}\n  }\n}\n`);
      } else {
        // A media axis that an attribute can also force (the layout tokens). Its tokens point at tokens on attribute
        // axes (density), whose blocks repeat them with the default context's value; each rule here therefore also
        // reaches the elements carrying those attributes, so the right context's value is declared there again.
        const attr = cfg.attribute.name;
        const reached = [...new Set([...onAxis, ...dependent].flatMap((t) => Object.keys(t.dependent)))]
          .map((a) => CONTEXT_CSS[a])
          .flatMap((c) => (c?.kind === 'attribute' ? [c.attribute] : []));
        const forced = `[${attr}="${cfg.attribute.values[context]}"]`;
        if (context !== def) {
          // Unforced pages: lower than a forced attribute below, equal to the attribute axes' blocks it follows.
          const selector = [`:root:not([${attr}])`, ...reached.map((a) => `:where(:root:not([${attr}])) [${a}]`)].join(',\n  ');
          out.push(`@media ${mediaQueryFor(model, axis, context)} {\n  ${selector} {\n${declarations(decls, '    ')}\n  }\n}\n`);
        }
        forcedBlocks.push(`${[forced, ...reached.map((a) => `${forced} [${a}]`)].join(',\n')} {\n${declarations(decls)}\n}\n`);
      }
    }
    out.push(...forcedBlocks.splice(0));
  }
  out.push(formatLayoutSwitch(model));
  return out.join('\n');
}

/**
 * An axis laid over another (the data palette over the theme), read on the root element only. The axis it lies over
 * already declares the default context's values; each other context gets one block per context of that axis, written
 * heavier than that axis's own blocks so it wins on the root and on any element inside that sets its own theme:
 *
 *   :root[data-palette="cockpit"], :root[data-palette="cockpit"] [data-theme="light"]                 the default theme
 *   :root[data-palette="cockpit"][data-theme="dark"], :root[data-palette="cockpit"] [data-theme="dark"]
 *   @media (prefers-color-scheme: dark) { :root[data-palette="cockpit"]:not([data-theme]) }          the reader's setting
 */
function formatLaidOver(model: Model, axis: string, tokens: ModelToken[]): string[] {
  const cfg = CONTEXT_CSS[axis]!;
  if (cfg.kind !== 'attribute' || !cfg.over) throw new Error(`The "${axis}" axis is not laid over another.`);
  const base = CONTEXT_CSS[cfg.over];
  const baseAxis = model.axes[cfg.over];
  if (base?.kind !== 'attribute' || !baseAxis) throw new Error(`The "${axis}" axis lies over "${cfg.over}", which is not an attribute axis.`);
  if (tokens.length === 0) return [];
  const { values, default: def } = model.axes[axis]!;
  const out = [`/* ${axis}: ${values.join(' | ')} (default ${def}), set on the root element; each ${cfg.over}'s values */`];
  for (const context of values) {
    if (context === def) continue;
    const root = `:root[${cfg.attribute}="${context}"]`;
    for (const b of baseAxis.values) {
      const key = combinationKey({ ...model.defaults, [cfg.over]: b, [axis]: context });
      const decls: Record<string, string> = {};
      for (const t of tokens) Object.assign(decls, t.css[key]);
      const own = `[${base.attribute}="${b}"]`;
      const selectors = b === baseAxis.default ? [root, `${root} ${own}`] : [`${root}${own}`, `${root} ${own}`];
      out.push(`${selectors.join(',\n')} {\n${declarations(decls)}\n}\n`);
      const pref = base.systemPreference?.[b];
      if (pref) out.push(`@media ${pref} {\n  ${root}:not([${base.attribute}]) {\n${declarations(decls, '    ')}\n  }\n}\n`);
    }
  }
  return out;
}

/** The layout switch: one inherited custom property, wide at and above the breakpoint, either form forceable by attribute. */
function formatLayoutSwitch(model: Model): string {
  const { property, attribute, values, default: def, wideQuery } = LAYOUT_SWITCH;
  const wide = values.find((v) => v !== def)!;
  return [
    `/* The layout switch: ${values.join(' | ')} (default ${def}). Read it with @container style(${property}: ${wide}) so a component follows the space it is in. The layout tokens above switch at the same width and follow the same attribute. */`,
    `:root,\n[${attribute}="${def}"] {\n  ${property}: ${def};\n}\n`,
    `@media ${substituteDimensions(model, wideQuery, 'The layout switch')} {\n  :root:not([${attribute}]) {\n    ${property}: ${wide};\n  }\n}\n`,
    `[${attribute}="${wide}"] {\n  ${property}: ${wide};\n}\n`,
  ].join('\n');
}

function formatTailwind(model: Model): string {
  const lines: string[] = [
    header('Tailwind theme. Utility names for the same custom properties; nothing here holds a value of its own.'),
    `/* Not in this theme, because Tailwind has no namespace for them: ${Object.keys(TAILWIND_NAMESPACE).length ? '' : ''}layer, opacity, border-width, focus, durations, typography composites, control/icon/target/selection/display sizes. Use the --${PREFIX}-* custom properties directly for those. */`,
    '@theme inline {',
  ];
  for (const t of model.tokens) {
    if (!t.emitted || t.type === 'typography') continue;
    const ns = TAILWIND_NAMESPACE[t.category];
    const name = ns?.(t.segments);
    if (!name) continue;
    lines.push(`  ${name}: var(${t.cssNames.value});`);
  }
  lines.push('}', '');
  return lines.join('\n');
}

function nest(tokens: ModelToken[], model: Model): Record<string, unknown> {
  const tree: Record<string, unknown> = {};
  for (const t of tokens) {
    let node = tree;
    for (const seg of t.segments.slice(0, -1)) node = (node[seg] ??= {}) as Record<string, unknown>;
    node[t.segments[t.segments.length - 1]!] = valueByContext(model, t);
  }
  return tree;
}

function formatTs(model: Model): string {
  const contexts = Object.fromEntries(
    Object.entries(model.axes).map(([axis, a]) => {
      const cfg = CONTEXT_CSS[axis]!;
      return [axis, { values: a.values, default: a.default, ...(cfg.kind === 'attribute' ? { attribute: cfg.attribute } : { media: Object.fromEntries(Object.keys(cfg.queries).map((c) => [c, mediaQueryFor(model, axis, c)])), ...(cfg.attribute ? { attribute: cfg.attribute.name, attributeValues: cfg.attribute.values } : {}) }) }];
    }),
  );
  const primitive = nest(model.tokens.filter((t) => t.tier === 'primitive'), model);
  const semantic = nest(model.tokens.filter((t) => t.tier === 'semantic'), model);
  const cssVariables = Object.fromEntries(
    model.tokens.filter((t) => t.emitted).map((t) => [t.path, t.type === 'typography' ? t.cssNames : t.cssNames.value]),
  );
  const j = (v: unknown) => JSON.stringify(v, null, 2);
  return [
    `// GENERATED by the simbolik token build — do not edit. Source: simbolik/tokens/. Rebuild with: npm run tokens:build`,
    ``,
    `/** The context switches and how each reaches CSS. */`,
    `export const contexts = ${j(contexts)} as const;`,
    ``,
    `/** Primitive tokens: raw, context-free values. Never consumed by components. */`,
    `export const primitive = ${j(primitive)} as const;`,
    ``,
    `/** Semantic tokens. A value that changes with a context is an object keyed by that context's values. */`,
    `export const semantic = ${j(semantic)} as const;`,
    ``,
    `/** Token path -> CSS custom property name, for every token that reaches CSS. Typography tokens map to one name per part. */`,
    `export const cssVariables = ${j(cssVariables)} as const;`,
    ``,
    `export type TokenPath = keyof typeof cssVariables;`,
    ``,
    `/** Tokens on their way out: token path -> what to use instead (the standard's $deprecated). Each still works until the Release that removes it. */`,
    `export const deprecated = ${j(Object.fromEntries(model.tokens.filter((t) => t.deprecated !== undefined && t.deprecated !== false).map((t) => [t.path, t.deprecated])))} as const;`,
    ``,
  ].join('\n');
}

function formatJson(model: Model): string {
  const records = model.tokens.map((t) => ({
    path: t.path,
    type: t.type,
    tier: t.tier,
    category: t.category,
    emitted: t.emitted,
    css: t.emitted ? (t.type === 'typography' ? t.cssNames : t.cssNames.value) : null,
    axis: t.axis,
    ...(t.over ? { over: t.over } : {}),
    value: valueByContext(model, t),
    reference: typeof t.original === 'string' && t.original.startsWith('{') ? t.original : undefined,
    description: t.description,
    deprecated: t.deprecated,
  }));
  return JSON.stringify({ $generated: 'by the simbolik token build — do not edit', contexts: model.axes, tokens: records }, null, 2) + '\n';
}

export async function build(dir = TOKENS_DIR_DEFAULT): Promise<{ files: string[]; tokens: number; emitted: number }> {
  const source = loadTokenSource(dir);
  const problems = validate(source);
  if (problems.length) {
    throw new Error(`Token source is invalid:\n${problems.map((p) => `  ${p.path}: ${p.message}`).join('\n')}`);
  }
  const model = buildModel(source);
  await crossCheckWithStyleDictionary(source, model);

  StyleDictionary.registerFormat({ name: 'simbolik/css', format: () => formatCss(model) });
  StyleDictionary.registerFormat({ name: 'simbolik/tailwind', format: () => formatTailwind(model) });
  StyleDictionary.registerFormat({ name: 'simbolik/typescript', format: () => formatTs(model) });
  StyleDictionary.registerFormat({ name: 'simbolik/json', format: () => formatJson(model) });

  const sd = new StyleDictionary({
    tokens: treeFor(source, model.defaults),
    usesDtcg: true,
    log: { verbosity: 'silent', warnings: 'disabled' },
    platforms: {
      css: { transforms: [], buildPath: join(ROOT, 'css/'), files: [{ destination: 'tokens.css', format: 'simbolik/css' }, { destination: 'tailwind.css', format: 'simbolik/tailwind' }] },
      code: { transforms: [], buildPath: join(ROOT, 'output/'), files: [{ destination: 'tokens.ts', format: 'simbolik/typescript' }, { destination: 'tokens.json', format: 'simbolik/json' }] },
    },
  });
  await sd.buildAllPlatforms();
  return {
    files: ['css/tokens.css', 'css/tailwind.css', 'output/tokens.ts', 'output/tokens.json'],
    tokens: model.tokens.length,
    emitted: model.tokens.filter((t) => t.emitted).length,
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  build(resolvePath(process.argv[2] ?? TOKENS_DIR_DEFAULT))
    .then((r) => {
      console.log(`Built ${r.tokens} tokens (${r.emitted} reach CSS):`);
      for (const f of r.files) console.log(`  ${f}`);
    })
    .catch((e: Error) => {
      console.error(e.message);
      process.exit(1);
    });
}
