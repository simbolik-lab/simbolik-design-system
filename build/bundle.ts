/**
 * Bundle the token stylesheet and every component stylesheet into one file
 * for plain-HTML consumers: css/simbolik.css. Generated; never edited.
 *
 *   npm run css:bundle
 *
 * The same step copies the fonts and the icon font out of node_modules into
 * assets/ (generated, never edited): a project may hold a copy of a Release
 * bundle, and a copy carries no node_modules, so every project reads fonts and
 * icons from assets/, whether it links this folder or holds a copy. Every font address in
 * their stylesheets carries the package's version (?v=), so a changed font is a
 * new address. assets/fonts/fonts.css holds every family at every weight the tokens
 * name, so a page links one font stylesheet rather than one per family and weight.
 */
import { readdirSync, readFileSync, writeFileSync, existsSync, cpSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

export function bundle(): { files: string[]; out: string } {
  const files = ['css/tokens.css'];
  const components = join(ROOT, 'components');
  for (const name of readdirSync(components).sort()) {
    const css = join(components, name, `${name}.css`);
    if (existsSync(css)) files.push(`components/${name}/${name}.css`);
  }
  const header = `/* GENERATED by the simbolik css bundle — do not edit. Rebuild with: npm run css:bundle */\n`;
  const body = files.map((f) => `\n/* ---- ${f} ---- */\n${readFileSync(join(ROOT, f), 'utf8')}`).join('\n');
  const out = 'css/simbolik.css';
  writeFileSync(join(ROOT, out), header + body);
  return { files, out };
}

/** The font families the design system's tokens name; each is an @fontsource package. */
export const FONTS = ['funnel-display', 'geist', 'geist-mono'];

/** The one font stylesheet a page links, inside assets/: every family at every weight the tokens name. */
export const FONT_STYLESHEET = 'fonts/fonts.css';

/** The font weights the tokens name, each a stylesheet of its font package. */
export function fontWeights(): string[] {
  const { tokens } = JSON.parse(readFileSync(join(ROOT, 'output', 'tokens.json'), 'utf8')) as { tokens: { type: string; value: unknown }[] };
  return [...new Set(tokens.filter((t) => t.type === 'fontWeight').map((t) => String(t.value)))].sort();
}

/**
 * Copies the fonts and the Phosphor regular icon font into assets/, replacing
 * what was there. Each font package carries its own licence; Phosphor's sits
 * at its package's top, so it is copied into the icon font's own folder, as
 * its MIT licence asks of every copy: a project that copies that folder takes
 * the licence with it.
 */
export function assets(): string {
  const out = join(ROOT, 'assets');
  rmSync(out, { recursive: true, force: true });
  for (const f of FONTS) {
    cpSync(join(ROOT, 'node_modules', '@fontsource', f), join(out, 'fonts', f), { recursive: true });
    versionAddresses(join(out, 'fonts', f), packageVersion(join('@fontsource', f)));
  }
  writeFileSync(join(out, FONT_STYLESHEET), fontStylesheet(join(out, 'fonts')));
  cpSync(join(ROOT, 'node_modules', '@phosphor-icons', 'web', 'src', 'regular'), join(out, 'phosphor', 'regular'), { recursive: true });
  cpSync(join(ROOT, 'node_modules', '@phosphor-icons', 'web', 'LICENSE'), join(out, 'phosphor', 'regular', 'LICENSE'));
  versionAddresses(join(out, 'phosphor', 'regular'), packageVersion(join('@phosphor-icons', 'web')));
  return 'assets/';
}

/**
 * Every family's stylesheet at every weight the tokens name, in one file beside the family folders: their
 * @font-face rules as each package writes them, each address pointed into its family's folder. A page waits
 * for every stylesheet it links before it draws, so one file in place of fifteen. The weight stylesheets stay
 * where they were, so a page that links them still works.
 */
function fontStylesheet(fonts: string): string {
  const header = `/* GENERATED by the simbolik css bundle — do not edit. Every font the design tokens name: ${FONTS.join(', ')}, at ${fontWeights().join(', ')}. */\n`;
  return header + FONTS.flatMap((f) => fontWeights().map((w) => readFileSync(join(fonts, f, `${w}.css`), 'utf8').replace(/url\((["']?)\.\/files\//g, `url($1./${f}/files/`))).join('\n');
}

/** The version of an installed package, from its package.json. */
function packageVersion(name: string): string {
  return (JSON.parse(readFileSync(join(ROOT, 'node_modules', name, 'package.json'), 'utf8')) as { version: string }).version;
}

/**
 * Gives every font address in a folder's stylesheets its package's version, `url(./files/x.woff2?v=5.3.0)`.
 * Fonts are cached for a year and never asked about again, and their file names never change, so a
 * font changed in a later Release would otherwise reach a returning reader up to a year late: a new icon
 * would show as an empty box. With the version in the address, a changed font is a new address, and no
 * file moves. The query comes before any #fragment (Phosphor's svg names its font that way).
 */
function versionAddresses(folder: string, version: string): void {
  for (const name of readdirSync(folder)) {
    if (!name.endsWith('.css')) continue;
    const sheet = join(folder, name);
    const css = readFileSync(sheet, 'utf8').replace(/url\((["']?)([^"')?#]+)([?#][^"')]*)?\1\)/g, (all, quote: string, file: string, rest = '') => {
      if (/^(data|https?):/.test(file)) return all;
      const query = rest.startsWith('?') ? `${rest.split('#')[0]}&v=${version}` : `?v=${version}`;
      const fragment = rest.includes('#') ? rest.slice(rest.indexOf('#')) : '';
      return `url(${quote}${file}${query}${fragment}${quote})`;
    });
    writeFileSync(sheet, css);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const r = bundle();
  console.log(`Wrote ${r.out} from ${r.files.length} file(s).`);
  console.log(`Wrote ${assets()} (fonts: ${FONTS.join(', ')}, in one stylesheet, ${FONT_STYLESHEET}; Phosphor regular).`);
}
